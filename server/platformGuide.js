const norm = (s) => String(s || '').toLowerCase();

// จัดอันดับหัวข้อที่ตรงกับคำถาม: ชื่อหัวข้อ/คำสำคัญ ตรงกับข้อความ (ทั้งแบบข้อความมีคำสำคัญ และคำสำคัญมีส่วนของข้อความ)
function search(topic, max = 3) {
  const q = norm(topic).trim();
  if (!q) return [];
  const words = q.split(/[\s,;/]+/).filter((w) => w.length >= 2);
  const scored = SECTIONS.map((s, i) => {
    let score = 0;
    const title = norm(s.title);
    if (title.includes(q) || q.includes(title)) score += 6;
    for (const k of s.keywords) {
      const kw = norm(k);
      if (q.includes(kw)) score += kw.length >= 4 ? 3 : 2;
      else if (words.some((w) => kw.includes(w) && w.length >= 3)) score += 1;
    }
    for (const w of words) if (title.includes(w)) score += 2;
    if (!score && words.some((w) => norm(s.text).includes(w) && w.length >= 4)) score = 0.5;
    return { i, s, score };
  }).filter((x) => x.score > 0).sort((a, b) => b.score - a.score || a.i - b.i);
  return scored.slice(0, max).map((x) => x.s);
}

const index = () => SECTIONS.map((s, i) => `${i + 1}. ${s.title}`);
const fullText = () => SECTIONS.map((s, i) => `## ${i + 1}. ${s.title}\n${s.text}`).join('\n\n');

module.exports = { GUIDE_CATEGORY, SECTIONS, search, index, fullText };
