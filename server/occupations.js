// "สถานะปัจจุบัน" ของผู้ใช้ (หมวดหลัก + หัวข้อย่อย + รายละเอียด) — เป็นฐานข้อมูลกลางสำหรับการค้นหา/เชื่อมต่อข้อมูลในฟีเจอร์ต่อไป
// ตอนนี้ยังเป็นข้อมูลส่วนตัว ไม่โชว์ให้ใครเห็น (ใช้แค่ให้เลขารู้จักผู้ใช้ และเตรียมไว้สำหรับฟีเจอร์ถัดไป)
const OCCUPATIONS = {
  'นักเรียน / นักศึกษา': ['ประถมศึกษา', 'มัธยมศึกษา', 'อาชีวศึกษา (ปวช./ปวส.)', 'อุดมศึกษา (ปริญญาตรีขึ้นไป)'],
  'ค้าขาย / ธุรกิจส่วนตัว': ['ขายอาหารตามสั่ง/เครื่องดื่ม', 'ขายของชำ', 'ขายเสื้อผ้า/แฟชั่น', 'ค้าขายออนไลน์', 'เจ้าของกิจการ/SME'],
  'พนักงานบริษัท / เอกชน': ['พนักงานออฟฟิศ/ธุรการ', 'พนักงานขาย/การตลาด', 'พนักงานโรงงาน/ฝ่ายผลิต', 'ช่างเทคนิค/วิศวกร', 'ไอที/โปรแกรมเมอร์'],
  'ข้าราชการ / รัฐวิสาหกิจ': ['ครู/อาจารย์/บุคลากรทางการศึกษา', 'ทหาร/ตำรวจ', 'ข้าราชการพลเรือน', 'พนักงานรัฐวิสาหกิจ'],
  'บุคลากรทางการแพทย์': ['แพทย์', 'พยาบาล', 'เภสัชกร', 'ทันตแพทย์', 'เจ้าหน้าที่สาธารณสุข/กู้ภัย'],
  'เกษตรกร / ประมง / ปศุสัตว์': ['ทำนา/ทำไร่', 'ทำสวนผลไม้/พืชผัก', 'เลี้ยงสัตว์/ปศุสัตว์', 'ทำประมง'],
  'อาชีพอิสระ / รับจ้างทั่วไป': ['ฟรีแลนซ์', 'ขับรถรับจ้าง/ไรเดอร์', 'ช่างก่อสร้าง/ซ่อมบำรุง', 'แม่บ้าน/รปภ.'],
  'อื่นๆ / ไม่ได้ประกอบอาชีพ': ['พ่อบ้าน/แม่บ้าน', 'เกษียณอายุ', 'ว่างงาน', 'อื่นๆ (โปรดระบุ)'],
};
const OTHER_SUB = 'อื่นๆ (โปรดระบุ)';
const MAX_DETAIL = 200;

// ตรวจและทำความสะอาดข้อมูลสถานะที่ผู้ใช้ส่งมา — main ว่าง = ล้างสถานะทั้งหมด
function validateOccupation(main, sub, detail) {
  const m = String(main || '').trim();
  if (!m) return { main: null, sub: null, detail: null };
  if (!Object.prototype.hasOwnProperty.call(OCCUPATIONS, m)) throw new Error('หมวดสถานะ/อาชีพไม่ถูกต้อง');
  const s = String(sub || '').trim();
  if (s && !OCCUPATIONS[m].includes(s)) throw new Error('หัวข้อย่อยไม่ตรงกับหมวดที่เลือก');
  const d = String(detail || '').replace(/[\u0000-\u001f\u007f]/g, ' ').split(/\s+/).join(' ').trim();
  if (d.length > MAX_DETAIL) throw new Error(`รายละเอียดยาวเกิน ${MAX_DETAIL} ตัวอักษร`);
  if (s === OTHER_SUB && d.length < 2) throw new Error('เลือก "อื่นๆ" ต้องกรอกรายละเอียดด้วย');
  return { main: m, sub: s || null, detail: d || null };
}

// ข้อความสั้นๆ สำหรับแสดง/ใส่ใน prompt เช่น "ข้าราชการ / รัฐวิสาหกิจ › ครู/อาจารย์… — สอนคณิตศาสตร์ ม.ต้น"
function describe(main, sub, detail) {
  if (!main) return '';
  return [main, sub].filter(Boolean).join(' › ') + (detail ? ' — ' + detail : '');
}

module.exports = { OCCUPATIONS, OTHER_SUB, MAX_DETAIL, validateOccupation, describe };
