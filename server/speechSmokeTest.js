// ทดสอบการเตรียมข้อความให้เลขาเสียงอ่าน (ทศนิยม เดือนย่อ ฯลฯ):  node server/speechSmokeTest.js
const path = require('path');
const { forSpeech, chunkText, forMaleVoice } = require(path.join(__dirname, '..', 'public', 'speech.js'));

let failures = 0;
const check = (label, ok, extra) => { if (!ok) failures++; console.log(`${ok ? '✅' : '❌'} ${label}${extra ? '  → ' + extra : ''}`); };
const eq = (label, input, expected) => { const got = forSpeech(input); check(label, got === expected, got === expected ? '' : `ได้ "${got}" ต้องการ "${expected}"`); };

// ---- เสียงชาย: คำลงท้ายผู้หญิง → ผู้ชาย (เฉพาะตอนอ่านออกเสียง) ----
const male = (label, input, expected) => { const got = forMaleVoice(input); check(label, got === expected, got === expected ? '' : `ได้ "${got}" ต้องการ "${expected}"`); };
male('สวัสดีค่ะ → สวัสดีครับ', 'สวัสดีค่ะ คุณต้น', 'สวัสดีครับ คุณต้น');
male('นะคะ → นะครับ', 'ได้เลยนะคะ', 'ได้เลยนะครับ');
male('คำถามลงท้ายคะ → ครับ', 'ใช่ไหมคะ ช่วยอะไรดีคะ', 'ใช่ไหมครับ ช่วยอะไรดีครับ');
male('"คะแนน" ไม่ถูกแก้ (คะ อยู่กลางคำ)', 'คะแนนสอบ 80 คะแนนค่ะ', 'คะแนนสอบ 80 คะแนนครับ');
male('"คะนอง/คะเน" ไม่ถูกแก้', 'ประมาณการคะเน', 'ประมาณการคะเน');
male('ดิฉัน → ผม', 'ดิฉันจะช่วยดูให้ค่ะ', 'ผมจะช่วยดูให้ครับ');
male('ข้อความที่ไม่มีคำลงท้ายผู้หญิง ไม่เปลี่ยน', 'ราคากุ้งวันนี้ 150 บาท', 'ราคากุ้งวันนี้ 150 บาท');
male('ค่าว่าง ไม่พัง', '', '');

// ---- ทศนิยม ----
eq('0.25 → 0 จุด 25', 'ADG 0.25', 'ADG 0 จุด 25');
eq('ทศนิยมหลายตัวในประโยค', 'ราคา 12.5 และ 3.05 บาท', 'ราคา 12 จุด 5 และ 3 จุด 05 บาท');
eq('เลขเวอร์ชัน 1.4.0 อ่านทุกจุด', 'Excel v1.4.0', 'Excel v1 จุด 4 จุด 0');
eq('จุดท้ายประโยคหลังตัวเลขไม่ถูกแปลง', 'ราคา 150 บาท. ขอบคุณ', 'ราคา 150 บาท. ขอบคุณ');
eq('เลขหลักพัน 1,500 → 1500', 'ต้นทุน 1,500 บาท', 'ต้นทุน 1500 บาท');
eq('คอมมาแยกรายการไม่ถูกลบ', 'กุ้ง 100,ปลา 20', 'กุ้ง 100,ปลา 20');
const ch = chunkText(forSpeech('กุ้ง ADG 0.25 ต่อวัน ราคา 150.50 บาท'));
check('ทศนิยมไม่ถูกตัดเป็นสองท่อน (ไม่อ่าน 0 แล้วหยุด)', ch.length === 1 && ch[0].includes('0 จุด 25') && ch[0].includes('150 จุด 50'), JSON.stringify(ch));

// ---- เดือนย่อ ----
const months = { 'ม.ค.': 'มกราคม', 'ก.พ.': 'กุมภาพันธ์', 'มี.ค.': 'มีนาคม', 'เม.ย.': 'เมษายน', 'พ.ค.': 'พฤษภาคม', 'มิ.ย.': 'มิถุนายน', 'ก.ค.': 'กรกฎาคม', 'ส.ค.': 'สิงหาคม', 'ก.ย.': 'กันยายน', 'ต.ค.': 'ตุลาคม', 'พ.ย.': 'พฤศจิกายน', 'ธ.ค.': 'ธันวาคม' };
for (const [abbr, full] of Object.entries(months)) eq(`${abbr} → ${full}`, `วันที่ 5 ${abbr} 2026`, `วันที่ 5 ${full} 2026`);
eq('พ.ย. ไม่มีจุดท้าย (พ.ย) ก็ได้', 'เมื่อ 19 พ.ย ที่ผ่านมา', 'เมื่อ 19 พฤศจิกายน ที่ผ่านมา');
eq('วันที่เต็ม 19 พ.ย. 2026', 'อ่านเมื่อ 19 พ.ย. 2026', 'อ่านเมื่อ 19 พฤศจิกายน 2026');
eq('หลายเดือนในประโยคเดียว', 'ตั้งแต่ ต.ค. ถึง ธ.ค. 2568', 'ตั้งแต่ ตุลาคม ถึง ธันวาคม 2568');
eq('ปี พ.ศ. / ค.ศ. อ่านเต็ม', 'พ.ศ. 2569 ตรงกับ ค.ศ. 2026', 'พุทธศักราช 2569 ตรงกับ คริสต์ศักราช 2026');
eq('ไม่แตะคำที่ตัวอักษรไทยติดหน้า (ไม่แทนมั่ว)', 'กรุงเทพ.ค.', 'กรุงเทพ.ค.');
eq('ข้อความที่ไม่มีเดือน/ตัวเลข ไม่เปลี่ยน', 'สวัสดีค่ะ มีอะไรให้ช่วยไหมคะ', 'สวัสดีค่ะ มีอะไรให้ช่วยไหมคะ');

// ---- การทำความสะอาดเดิมยังทำงาน ----
eq('ตัด markdown และอีโมจิ', '**สำคัญ** 😊 อ่าน [ลิงก์](https://x.com) ด้วย', 'สำคัญ อ่าน ลิงก์ ด้วย');
eq('ค่าว่าง/null ไม่พัง', null, '');
const two = chunkText(forSpeech('ประโยคแรก. ประโยคสอง!'));
check('จบประโยคจริง (จุด+เว้นวรรค) ยังตัดท่อนตามปกติได้', two.join(' ') === 'ประโยคแรก. ประโยคสอง!');

console.log(failures ? `\n❌ ไม่ผ่าน ${failures} ข้อ` : '\n✅ ผ่านทุกข้อ');
process.exit(failures ? 1 : 0);
